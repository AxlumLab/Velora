void XamlCompiler::emit()
{
    const std::string sourceName = m_path.filename().string();
    const bool hasItems = std::ranges::any_of(m_templates, [](const auto& t) { return t->isItemTemplate(); });
    std::ostringstream h, s;
    h << "// Generated by velorac from " << sourceName << "; do not edit.\n#pragma once\n\n"
      << "#include <velora/data/Observable.hpp>\n"
      << "#include <velora/runtime/Framework.hpp>\n";
    if (hasItems)
        h << "#include <velora/runtime/Items.hpp>\n";
    h << "\n#include <array>\n#include <memory>\n#include <type_traits>\n\n";
    for (const auto& include : m_includes)
        h << "#include " << cppString(include) << "\n";
    for (const auto& include : m_viewIncludes)
        h << "#include " << cppString(include) << "\n";
    if (!m_class.ns.empty())
        h << "\nnamespace " << m_class.ns << " {\n";
    s << "// Generated by velorac from " << sourceName << "; do not edit.\n#include "
      << cppString(m_result.headerName) << "\n";
    if (!m_class.ns.empty())
        s << "\nnamespace " << m_class.ns << " {\n";

    emitClass(m_page, h, s, m_page.cls);
    for (const auto& t : m_templates)
        emitClass(*t, h, s, m_page.cls + "::" + t->cls);

    if (!m_class.ns.empty())
    {
        h << "\n}  // namespace " << m_class.ns << "\n";
        s << "\n}  // namespace " << m_class.ns << "\n";
    }
    m_result.header = h.str();
    m_result.source = s.str();
}

void XamlCompiler::emitClass(const XamlScope& c, std::ostringstream& h, std::ostringstream& s,
                             const std::string& qualified)
{
    const std::string& name = c.cls;
    const std::string item = c.rootType;
    h << "\n";
    if (c.isControlTemplate())
    {
        h << "// One instance of a ControlTemplate: its own elements and name scope under the templated\n"
          << "// element (the owner). Destroying it removes them.\n"
          << "class " << qualified << " final {\npublic:\n";
    }
    else if (c.isItemTemplate())
    {
        h << "// Container built from a DataTemplate (x:DataType " << item << "). bind() points it at an\n"
          << "// item, or at none; its bindings and handlers always follow the current item.\n"
          << "class " << qualified << " final {\npublic:\n";
    }
    else
    {
        h << "// View of " << m_path.filename().string()
          << ". The controller must outlive the view; destroying the view\n"
          << "// removes its elements together with every event handler and binding attached to them.\n"
          << "class " << name << " final {\npublic:\n";
        for (const auto& t : m_templates)
            h << "    class " << t->cls << ";\n"; // item and control templates
        if (!m_templates.empty())
            h << "\n";
    }
    // Each name carries the kind of the element it names (a custom control is its UserControl
    // root), and converts to the ElementId accepted by the Framework APIs.
    h << "    struct Names {\n";
    for (const auto& n : c.nameOrder)
        h << "        velora::TypedElementId<velora::ElementKind::k" << c.nameTypes.at(n) << "> " << n
          << ";\n";
    h << "    };\n\n";
    if (c.isControlTemplate())
        h << "    " << name << "(velora::Framework& ui, velora::ElementId owner);\n";
    else if (c.isItemTemplate())
        h << "    " << name << "(velora::Framework& ui, " << m_class.name
          << "& controller, velora::ElementId parent);\n";
    else
        h << "    " << name << "(velora::Framework& ui, " << m_class.name
          << "& controller, velora::ElementId parent = 0);\n";
    h << "    ~" << name << "();\n"
      << "    " << name << "(const " << name << "&) = delete;\n"
      << "    " << name << "& operator=(const " << name << "&) = delete;\n\n"
      << "    velora::ElementId root() const noexcept { return m_elements[0]; }\n"
      << "    const Names& names() const noexcept { return m_names; }\n";
    if (c.isItemTemplate())
    {
        h << "    ::" << item << "* item() const noexcept { return m_item; }\n"
          << "    void bind(::" << item << "* item);\n";
    }
    if (!c.isControlTemplate())
        h << "    // Re-reads every OneWay and TwoWay x:Bind source (needed only for sources that do not "
             "notify).\n"
          << "    void updateBindings();\n";
    for (std::size_t k = 0; k < c.repeaters.size(); ++k)
        if (!c.repeaters[k].name.empty())
            h << "    velora::ItemsRepeater<::" << c.repeaters[k].item << ", " << c.repeaters[k].tmpl << ">& "
              << c.repeaters[k].name << "Items() noexcept { return *m_items" << k << "; }\n";
    h << "\nprivate:\n";
    for (std::size_t k = 0; k < c.live.size(); ++k)
        h << "    void track" << k << "();\n    void apply" << k << "();\n";
    h << "    velora::Framework& m_ui;\n";
    if (c.isControlTemplate())
        h << "    velora::ElementId m_owner;\n";
    else
        h << "    " << m_class.name << "& m_controller;\n";
    if (c.isItemTemplate())
        h << "    ::" << item << "* m_item = nullptr;\n";
    h << "    std::array<velora::ElementId, " << c.elements << "> m_elements{};\n    Names m_names;\n";
    for (std::size_t k = 0; k < c.children.size(); ++k)
        h << "    std::unique_ptr<::" << c.children[k] << "> m_child" << k << ";\n"
          << "    std::unique_ptr<::" << c.children[k] << "_xaml> m_childView" << k << ";\n";
    for (std::size_t k = 0; k < c.repeaters.size(); ++k)
        h << "    std::unique_ptr<velora::ItemsRepeater<::" << c.repeaters[k].item << ", "
          << c.repeaters[k].tmpl << ">> m_items" << k << ";\n";
    for (std::size_t k = 0; k < c.controlTemplates.size(); ++k)
        h << "    std::unique_ptr<" << c.controlTemplates[k] << "> m_template" << k << ";\n";
    for (std::size_t k = 0; k < c.live.size(); ++k)
    {
        h << "    std::array<velora::Subscription, " << c.live[k].names.size() << "> m_bind" << k << ";\n";
        if (c.live[k].guarded)
            h << "    bool m_writing" << k << " = false;\n";
    }
    h << "};\n";

    // Source.
    const auto bindAll = [&](const char* indent)
    {
        for (std::size_t k = 0; k < c.live.size(); ++k)
            s << indent << "track" << k << "();\n" << indent << "apply" << k << "();\n";
    };
    if (c.isControlTemplate())
        s << "\n"
          << qualified << "::" << name << "(velora::Framework& ui, velora::ElementId owner)\n"
          << "    : m_ui(ui), m_owner(owner) {\n    [[maybe_unused]] const auto& p = m_ui.props();\n";
    else
        s << "\n"
          << qualified << "::" << name << "(velora::Framework& ui, " << m_class.name
          << "& controller, velora::ElementId parent)\n"
          << "    : m_ui(ui), m_controller(controller) {\n    [[maybe_unused]] const auto& p = "
             "m_ui.props();\n";
    for (const auto& statement : c.build)
        s << statement;
    if (c.isControlTemplate())
    {
        s << "    m_ui.applyTemplate(m_owner, m_elements[0], {";
        for (const auto& n : c.nameOrder)
            s << "{" << cppString(n) << ", m_names." << n << "}, ";
        s << "});\n";
        for (const auto& statement : c.states)
            s << statement;
    }
    for (const auto& [key, statements] : c.handlers)
    {
        s << std::format("    m_ui.on(m_elements[{}], m_ui.events().{}, [this] {{\n", key.first, key.second);
        if (c.isItemTemplate())
            s << "        if (!m_item) return;\n";
        for (const auto& statement : statements)
            s << statement;
        s << "    });\n";
    }
    if (!c.isItemTemplate())
    {
        for (const auto& statement : c.once)
            s << statement;
        bindAll("    ");
    }
    s << "}\n\n"
      << qualified << "::~" << name << "() {\n"
      << "    if (m_ui.tree().contains(m_elements[0])) m_ui.tree().remove(m_elements[0]);\n}\n";
    if (c.isItemTemplate())
    {
        s << "\nvoid " << qualified << "::bind(::" << item << "* item) {\n"
          << "    m_item = item;\n";
        for (std::size_t k = 0; k < c.live.size(); ++k)
            s << "    for (auto& subscription : m_bind" << k << ") subscription.reset();\n";
        s << "    [[maybe_unused]] const auto& p = m_ui.props();\n"
          << "    if (!m_item) {\n";
        for (const auto& statement : c.unbind)
            s << "    " << statement;
        s << "        m_ui.tree().clearProperty(m_elements[0], *p.DataContext, "
             "velora::PropertySource::kLocal);\n"
          << "        return;\n    }\n"
          << "    // The container's DataContext is its item, so {Binding} inside the template reads it.\n"
          << "    m_ui.set(m_elements[0], p.DataContext, "
             "velora::PropertyValue(velora::ObjectRef::borrow(*m_item)));\n";
        for (const auto& statement : c.once)
            s << statement;
        bindAll("    ");
        s << "}\n";
    }
    if (c.isControlTemplate())
        return;
    s << "\nvoid " << qualified << "::updateBindings() {\n";
    if (c.isItemTemplate())
        s << "    if (!m_item) return;\n";
    bindAll("    ");
    for (const auto& statement : c.refresh)
        s << statement;
    s << "}\n";
    for (std::size_t k = 0; k < c.live.size(); ++k)
    {
        const auto& b = c.live[k];
        s << "\nvoid " << qualified << "::track" << k << "() {\n";
        for (std::size_t i = 0; i < b.names.size(); ++i)
        {
            const bool last = i + 1 == b.names.size();
            s << std::format("    m_bind{}[{}] = velora::observe({}, velora::propertyId({}), [this] {{ "
                             "{}apply{}(); }});\n",
                             k, i, b.owners[i], cppString(b.names[i]),
                             last ? "" : std::format("track{}(); ", k), k);
        }
        s << "}\n\nvoid " << qualified << "::apply" << k << "() {\n";
        if (b.guarded)
            s << "    if (m_writing" << k << ") return;\n";
        s << "    [[maybe_unused]] const auto& p = m_ui.props();\n" << b.apply << "}\n";
    }
}

CompileResult compile(std::string_view source, const std::filesystem::path& path,
                      const CompileOptions& options)
{
    CompileResult result;
    auto parsed = parseXaml(source);
    result.diagnostics = std::move(parsed.diagnostics);
    if (!result.ok() || !parsed.document.root)
        return result;
    XamlCompiler(path, options, result).run(parsed.document);
    XamlCompiler::sortDiagnostics(result.diagnostics);
    return result;
}

CompileResult checkResources(std::string_view source, const std::filesystem::path& path,
                             const CompileOptions& options)
{
    CompileResult result;
    auto parsed = parseXaml(source);
    result.diagnostics = std::move(parsed.diagnostics);
    if (!result.ok() || !parsed.document.root)
        return result;
    XamlCompiler(path, options, result).checkDictionary(parsed.document);
    XamlCompiler::sortDiagnostics(result.diagnostics);
    return result;
}

